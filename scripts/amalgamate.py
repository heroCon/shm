#!/usr/bin/env python3
"""Regenerate single_include/shm_pubsub.hpp. The CI job fails if the result differs."""

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
INCLUDE = ROOT / "include"
OUT = ROOT / "single_include" / "shm_pubsub.hpp"

# Public headers, in include order. Each pulls its "shm_pubsub/..." includes once.
ENTRY = [
    "shm_pubsub/shm_pubsub.hpp",
    "shm_pubsub/typed.hpp",
    "shm_pubsub/eventfd_bridge.hpp",
    "shm_pubsub/io_uring.hpp",
]


def absorb(rel, seen, out):
    if rel in seen:
        return
    seen.add(rel)
    for line in (INCLUDE / rel).read_text().splitlines(True):
        match = re.match(r'#include "shm_pubsub/([^"]+)"\n', line)
        if match:
            absorb("shm_pubsub/" + match.group(1), seen, out)
        else:
            out.append(line)


def main():
    seen = set()
    parts = [
        "// Generated by scripts/amalgamate.py from include/shm_pubsub.\n",
        "// Do not edit this file; regenerate it.\n\n",
    ]
    for entry in ENTRY:
        absorb(entry, seen, parts)
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("".join(parts))
    print("wrote %s (%d bytes)" % (OUT, OUT.stat().st_size))


if __name__ == "__main__":
    main()
